const QRegularExpression &cantillation()
{
    static const QRegularExpression expression(QStringLiteral("[\\x{0591}-\\x{05AF}]"));
    return expression;
}

const QRegularExpression &punctuation()
{
    static const QRegularExpression expression(
        QStringLiteral("[\\p{P}\\p{S}]"),
        QRegularExpression::UseUnicodePropertiesOption);
    return expression;
}

QHash<QString, QString> readIndex(const QJsonObject &source)
{
    QHash<QString, QString> index;
    index.reserve(source.size());
    for (auto item = source.constBegin(); item != source.constEnd(); ++item) {
        QStringList numbers;
        const QJsonArray candidates = item.value().toArray();
        numbers.reserve(candidates.size());
        for (const QJsonValue &candidate : candidates) {
            numbers.append(candidate.toString());
        }
        index.insert(item.key(), numbers.join(QLatin1Char(' ')));
    }
    return index;
}

/// Whether a form and the entry it is filed under could be the same word, at
/// the weakest strength that says anything at all: they share a consonant.
///
/// Deliberately this weak. Hebrew loses radicals freely — נָתַן is written תֵּן,
/// הָלַךְ is written לֵךְ — so anything stricter starts refusing real
/// inflections. What it does catch is a pairing that cannot be a spelling of
/// the same word under any morphology, which is what a join built by counting
/// co-occurrences in a corpus will occasionally produce.
bool couldBeTheSameWord(const QString &form, const QString &lemma)
{
    const QString written = foldedKey(form);
    const QString root = foldedKey(lemma);
    if (written.isEmpty() || root.isEmpty()) {
        // Nothing to judge on, so nothing to object to.
        return true;
    }
    for (const QChar letter : written) {
        if (root.contains(letter)) {
            return true;
        }
    }
    return false;
}

/// Drops the candidates an index names that its own entries contradict.
///
/// The shipped index is generated by counting which Strong's numbers each
/// inflected form appears with in the Westminster Leningrad Codex, and a form
/// can pick up the number of the word beside it. Two rows of the current file
/// do: `בו` "in him" is filed under H8055 שָׂמַח "to rejoice", and `לי` "to me"
/// under H7121 קָרָא "to call" — both prepositions carrying a pronominal
/// suffix, which Strong's has no entry for at all, wearing the number of the
/// verb they follow.
///
/// Done once here rather than inside numbersFor(): the test needs the entry's
/// lemma, and the alignment asks strongsFor() for every token of every witness.
/// One pass beside a multi-megabyte parse costs nothing; a pass per lookup
/// would be felt.
void pruneIndex(
    QHash<QString, QString> &index,
    const QHash<QString, LexiconEntry> &entries)
{
    for (auto item = index.begin(); item != index.end();) {
        const QStringList numbers =
            item.value().split(QLatin1Char(' '), Qt::SkipEmptyParts);
        QStringList kept;
        kept.reserve(numbers.size());
        for (const QString &number : numbers) {
            const auto entry = entries.constFind(number);
            // A number with no entry shipped says nothing about itself, so
            // there is nothing for it to disagree with. It still reaches the
            // marker as a bare number, which is what it always did.
            if (entry == entries.constEnd()
                || couldBeTheSameWord(item.key(), entry->lemma)) {
                kept.append(number);
            }
        }
        if (kept.isEmpty()) {
            item = index.erase(item);
        } else {
            item.value() = kept.join(QLatin1Char(' '));
            ++item;
        }
    }
}

HebrewLexicon parse(const QByteArray &json)
{
    HebrewLexicon lexicon;
    QJsonParseError error;
    const QJsonDocument document = QJsonDocument::fromJson(json, &error);
    if (error.error != QJsonParseError::NoError || !document.isObject()) {
        return lexicon;
    }
    return HebrewLexicon::fromJson(document.object());
}

