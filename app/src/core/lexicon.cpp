HebrewLexicon HebrewLexicon::fromJson(const QJsonObject &document)
{
    HebrewLexicon lexicon;
    lexicon.m_pointed = readIndex(document.value(QStringLiteral("pointed")).toObject());
    lexicon.m_forms = readIndex(document.value(QStringLiteral("forms")).toObject());

    const QJsonObject entries = document.value(QStringLiteral("entries")).toObject();
    lexicon.m_entries.reserve(entries.size());
    for (auto item = entries.constBegin(); item != entries.constEnd(); ++item) {
        const QJsonObject record = item.value().toObject();
        lexicon.m_entries.insert(
            item.key(),
            LexiconEntry{
                item.key(),
                record.value(QStringLiteral("l")).toString(),
                record.value(QStringLiteral("x")).toString(),
                record.value(QStringLiteral("p")).toString(),
                record.value(QStringLiteral("d")).toString(),
                record.value(QStringLiteral("g")).toString(),
                record.value(QStringLiteral("k")).toString(),
                record.value(QStringLiteral("bg")).toString(),
                record.value(QStringLiteral("bd")).toString(),
                record.value(QStringLiteral("m")).toString(),
            });
    }

    // Last, because it is the entries that judge the indexes.
    pruneIndex(lexicon.m_forms, lexicon.m_entries);
    pruneIndex(lexicon.m_pointed, lexicon.m_entries);
    return lexicon;
}

QString pointedKey(const QString &text)
{
    QString result = text.normalized(QString::NormalizationForm_D);
    result.remove(cantillation());
    result.remove(punctuation());
    return result.normalized(QString::NormalizationForm_C).trimmed();
}

QString strongsTooltip(const QList<LexiconEntry> &entries)
{
    if (entries.isEmpty()) {
        return QString();
    }

    QStringList blocks;
    for (const LexiconEntry &entry : entries) {
        QStringList lines;

        // Headline: the number, how the word is written and said, and what
        // part of speech it is.
        QStringList headline{entry.strongs};
        if (!entry.lemma.isEmpty()) {
            headline.append(entry.lemma);
        }
        if (!entry.transliteration.isEmpty()) {
            headline.append(QStringLiteral("(%1)").arg(entry.transliteration));
        }
        if (!entry.morphology.isEmpty()) {
            headline.append(QStringLiteral("[%1]").arg(entry.morphology));
        }
        lines.append(headline.join(QLatin1Char(' ')));

        if (!entry.briefGloss.isEmpty()) {
            lines.append(entry.briefGloss);
        }
        if (!entry.meaning.isEmpty()) {
            lines.append(QString());
            lines.append(entry.meaning);
        }

        // Strong's own wording last: it is the older and more slanted of the
        // two, and worth having but not worth leading with.
        if (!entry.gloss.isEmpty() && entry.gloss != entry.briefGloss) {
            lines.append(QString());
            lines.append(QStringLiteral("Strong's: %1").arg(entry.gloss));
        }
        if (!entry.derivation.isEmpty()) {
            lines.append(QStringLiteral("From: %1").arg(entry.derivation));
        }
        if (!entry.kjvUsage.isEmpty()) {
            lines.append(QStringLiteral("KJV: %1").arg(entry.kjvUsage));
        }

        blocks.append(lines.join(QLatin1Char('\n')));
    }

    if (blocks.size() > 1) {
        blocks.prepend(
            QStringLiteral("%1 possible readings:").arg(blocks.size()));
    }
    return blocks.join(QStringLiteral("\n\n"));
}

const HebrewLexicon &HebrewLexicon::shared()
{
    static const HebrewLexicon lexicon = [] {
        const QString path = locateDataFile(QStringLiteral("hebrew_lexicon.json"));
        HebrewLexicon loaded = path.isEmpty() ? HebrewLexicon() : fromFile(path);
        // A separate file, and an optional one: a data directory without it
        // simply has no opinion about roots. Kept out of the dictionary itself
        // because that is six megabytes on one line, and the roots are derived
        // from it rather than shipped with it.
        loaded.loadRoots(locateDataFile(QStringLiteral("hebrew_roots.json")));
        return loaded;
    }();
    return lexicon;
}

HebrewLexicon HebrewLexicon::fromFile(const QString &path)
{
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly)) {
        return HebrewLexicon();
    }
    return parse(file.readAll());
}

QStringList HebrewLexicon::strongsFor(const QString &word) const
{
    return numbersFor(word).split(QLatin1Char(' '), Qt::SkipEmptyParts);
}

void HebrewLexicon::loadRoots(const QString &path)
{
    if (path.isEmpty()) {
        return;
    }
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly)) {
        return;
    }
    const QJsonDocument document = QJsonDocument::fromJson(file.readAll());
    if (!document.isObject()) {
        return;
    }

    const QJsonObject roots =
        document.object().value(QStringLiteral("roots")).toObject();
    m_roots.reserve(roots.size());
    for (auto item = roots.constBegin(); item != roots.constEnd(); ++item) {
        const QString root = item.value().toString();
        // A word that is its own root tells the scorer nothing it does not
        // already get from the Strong's number itself.
        if (!root.isEmpty() && root != item.key()) {
            m_roots.insert(item.key(), root);
        }
    }
}

QStringList HebrewLexicon::rootsFor(const QString &word) const
{
    if (m_roots.isEmpty()) {
        return QStringList();
    }

    QStringList roots;
    for (const QString &number : strongsFor(word)) {
        const auto root = m_roots.constFind(number);
        if (root != m_roots.constEnd() && !roots.contains(root.value())) {
            roots.append(root.value());
        }
    }
    return roots;
}

QString HebrewLexicon::numbersFor(const QString &word) const
{
    // Pointed first: it distinguishes readings the consonants alone cannot.
    const QString pointed = pointedKey(word);
    if (!pointed.isEmpty()) {
        const auto match = m_pointed.constFind(pointed);
        if (match != m_pointed.constEnd()) {
            return match.value();
        }
    }

    const QString consonantal = comparisonKey(word);
    if (consonantal.isEmpty()) {
        return QString();
    }
    const auto match = m_forms.constFind(consonantal);
    if (match != m_forms.constEnd()) {
        return match.value();
    }

    // Hebrew prefixes agglutinate and the index holds the forms the Masoretic
    // text happens to use, so a word carrying an extra prefix misses. Peeling
    // one or two prefix letters recovers most of those. The stripped form is
    // only accepted when it is itself in the index, which keeps the heuristic
    // from inventing readings out of coincidental letter sequences.
    for (int peeled = 1; peeled <= 2 && peeled + 1 < consonantal.size(); ++peeled) {
        if (!isPrefixLetter(consonantal.at(peeled - 1))) {
            break;
        }
        const auto stripped = m_forms.constFind(consonantal.mid(peeled));
        if (stripped != m_forms.constEnd()) {
            return stripped.value();
        }
    }

    return QString();
}

QList<LexiconEntry> HebrewLexicon::lookup(const QString &word) const
{
    QList<LexiconEntry> result;
    const QString numbers = numbersFor(word);
    if (numbers.isEmpty()) {
        return result;
    }

    for (const QString &number : numbers.split(QLatin1Char(' '), Qt::SkipEmptyParts)) {
        const auto entry = m_entries.constFind(number);
        if (entry != m_entries.constEnd()) {
            result.append(entry.value());
        } else {
            result.append(LexiconEntry{number, QString(), QString(), QString()});
        }
    }
    return result;
}

bool HebrewLexicon::knows(const QString &word) const
{
    return !numbersFor(word).isEmpty();
}

